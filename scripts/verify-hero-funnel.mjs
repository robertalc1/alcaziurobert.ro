import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base=process.env.AUDIT_URL || 'http://127.0.0.1:4177';
const output=process.env.AUDIT_OUTPUT || 'artifacts.local/hero-funnel/after';
await mkdir(output,{recursive:true});
const browser=await chromium.launch();const results=[];
const userAgent='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/145.0.0.0 Safari/537.36';
try {
 for(const [width,height] of [[360,640],[390,844],[768,1024],[1440,900]]) {
  const page=await browser.newPage({viewport:{width,height},reducedMotion:'reduce',userAgent});
  const errors=[];const videos=[];page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(r.url().endsWith('.mp4'))videos.push(r.url())});
  await page.goto(base,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Acceptă necesare',exact:true}).click();
  assert.equal(await page.locator('h1').count(),1);assert.equal(await page.locator('.hero-services li').count(),3);
  assert.equal(await page.locator('.faq-trigger').count(),5);
  const cta=await page.locator('.hero-cta').boundingBox();assert.ok(cta.y+cta.height<=height,`CTA visible ${width}`);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${output}/hero-${width}.png`});
  await page.locator('.hero-cta').focus();await page.keyboard.press('Enter');
  const target=await page.locator('#offer').boundingBox();
  const nav=await page.locator('.site-nav').boundingBox();
  assert.ok(target.y>=nav.y+nav.height-1,`Offer clears fixed navigation: ${target.y} vs ${nav.y+nav.height}`);
  assert.equal(await page.evaluate(()=>document.activeElement?.id),'offer');
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(videos.length,0,'Video is not downloaded before play');
  await page.locator('#presentation').scrollIntoViewIfNeeded();
  await page.locator('#presentation').screenshot({path:`${output}/vsl-${width}.png`});
  await page.locator('.vsl-play').click();
  await page.waitForFunction(()=>document.querySelector('video').currentTime>.2 && document.querySelector('video').textTracks[0]?.cues?.length>5);
  const playback=await page.locator('video').evaluate(v=>({duration:v.duration,controls:v.controls,tracks:v.textTracks.length,cues:v.textTracks[0]?.cues?.length,muted:v.muted}));
  assert.ok(playback.duration>70&&playback.duration<85);assert.equal(playback.controls,true);assert.equal(playback.tracks,1);assert.ok(playback.cues>5);
  await page.locator('video').evaluate(v=>v.pause());
  for(const option of await page.locator('.funnel-options summary').all())await option.click();
  await page.locator('#compounding').screenshot({path:`${output}/options-${width}.png`});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.equal(await page.locator('#ga4-gtag-script').count(),0);
  assert.deepEqual(errors,[]);
  results.push({width,height,ctaAboveFold:true,offerOffset:Math.round(target.y),video:playback,overflow:false,errors});await page.close();
 }
 const context=await browser.newContext({viewport:{width:1440,height:900},userAgent});
 await context.route('**/gtag/js*',r=>r.fulfill({contentType:'application/javascript',body:''}));
 await context.route('**/fbevents.js',r=>r.fulfill({contentType:'application/javascript',body:''}));
 const page=await context.newPage();await page.goto(base);await page.getByRole('button',{name:'Acceptă toate',exact:true}).click();
 await page.waitForSelector('#ga4-gtag-script',{state:'attached'});
 await page.locator('.hero-cta').click();await page.locator('.vsl-play').click();
 await page.waitForFunction(()=>document.querySelector('video').currentTime>.3);
 await page.locator('video').evaluate(v=>{v.pause();v.currentTime=v.duration-.5;return v.play()});
 await page.waitForFunction(()=>document.querySelector('video').ended);
 await page.locator('video').evaluate(v=>{v.currentTime=0;return v.play()});await page.locator('video').evaluate(v=>v.pause());
 await page.locator('.funnel-options summary').first().click();
 await page.waitForFunction(()=>(window.dataLayer||[]).some(x=>x[0]==='event'&&x[1]==='view_service_options'));
 const events=await page.evaluate(()=>(window.dataLayer||[]).filter(x=>x[0]==='event').map(x=>({name:x[1],params:x[2]})));
 for(const name of ['explore_services','video_start','video_complete','view_service_options'])assert.equal(events.filter(x=>x.name===name).length,1,name);
 assert.equal(events.filter(x=>x.name==='quote_request').length,0,'Exploration is distinct from quote requests');
 results.push({consentedEvents:events});
 await page.evaluate(()=>{document.documentElement.style.zoom='2'});await page.locator('#hero').scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'200% zoom');
 await page.screenshot({path:`${output}/zoom-200.png`});
 await page.evaluate(()=>{document.documentElement.style.zoom='1';localStorage.setItem('lang','en')});await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 assert.ok((await page.locator('h1').innerText()).includes('A premium website.'));
 assert.ok((await page.locator('.hero-price').innerText()).includes('€1,000'));
 assert.ok((await page.locator('.vsl-play').innerText()).includes('Romanian'));
 await page.setViewportSize({width:360,height:640});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'English mobile');
 await page.screenshot({path:`${output}/english-360.png`});
 await page.close();await context.close();
 await writeFile(`${output}/verification.json`,JSON.stringify(results,null,2));console.log(JSON.stringify(results,null,2));
}finally{await browser.close()}
